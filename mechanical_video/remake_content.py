def validate_editorial():
    assert sorted(EPISODES) == list(range(1,13))
    for n,(title,shots) in EPISODES.items():
        assert len(shots)==8 and sum(s[2] for s in shots)>=90
        for area,action,seconds,lines in shots:
            assert all(0<len(line)<=20 and '\n' not in line for line in lines), (n,lines)
    return True


